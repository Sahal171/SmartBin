import React, { useState } from 'react';
import { Search } from 'lucide-react';
import ErrorMessage from './ErrorMessage';

export default function RetrieveForm({ onRetrieve, isLoading, error }) {
  const [code, setCode] = useState('');

  const handleSubmit = (e) => {
    e.preventDefault();
    const cleanCode = code.trim().toUpperCase();
    if (!cleanCode) return;
    onRetrieve(cleanCode);
  };

  const handleInputChange = (e) => {
    const val = e.target.value.toUpperCase().replace(/[^A-Z0-9]/g, '');
    if (val.length <= 10) {
      setCode(val);
    }
  };

  return (
    <div className="card" style={{ maxWidth: '540px', margin: '0 auto' }}>
      <div style={{ textAlign: 'center', marginBottom: '1.5rem' }}>
        <h2 style={{ fontSize: '1.5rem', fontWeight: 700, color: 'var(--gray-900)', marginBottom: '0.5rem' }}>
          Retrieve Your File
        </h2>
        <p style={{ color: 'var(--gray-500)', fontSize: '0.9375rem' }}>
          Enter the 6-character transfer code generated by SmartBin.
        </p>
      </div>

      <ErrorMessage message={error} />

      <form onSubmit={handleSubmit}>
        <div className="code-input-group">
          <input
            type="text"
            className="code-input"
            placeholder="e.g. 7K4P92"
            value={code}
            onChange={handleInputChange}
            maxLength={10}
            autoFocus
            disabled={isLoading}
          />
        </div>

        <button
          type="submit"
          disabled={!code.trim() || isLoading}
          className="btn btn-primary btn-full btn-lg"
        >
          {isLoading ? (
            <>
              <div className="spinner" style={{ width: '20px', height: '20px' }}></div>
              <span>Searching...</span>
            </>
          ) : (
            <>
              <Search size={20} />
              <span>Retrieve File</span>
            </>
          )}
        </button>
      </form>
    </div>
  );
}
